#!/usr/bin/env node
// Writes public/sw.js (run by npm's prebuild). The service worker precaches every page the app has, so the
// whole revision set works offline: each page's HTML and the JS and CSS it loads. Chapters are read from the
// registry, so a new chapter is picked up on the next build with no change here.
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const reg = fs.readFileSync(path.join(root, 'lib', 'registry.ts'), 'utf8');
const chapters = [...reg.matchAll(/id: '([a-z]+)-ch(\d+)'/g)].map(m => ({ subject: m[1], id: `${m[1]}-ch${m[2]}` }));
const subjects = [...new Set(chapters.map(c => c.subject))];
const VIEWS = ['', 'vision', 'path', 'compare', 'connect', 'memory', 'solve', 'games', 'drill', 'hunt', 'mcq', 'flip', 'practice', 'notes', 'library', 'cheat', 'formulas'];

const urls = ['/', '/weak', '/account', ...subjects.flatMap(s => [`/${s}`, `/${s}/formulas`, `/${s}/last-day`]),
  ...chapters.flatMap(c => VIEWS.map(v => `/${c.subject}/${c.id}${v ? '/' + v : ''}`))];

const version = `cr-${new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)}`;
const sw = `// Generated by scripts/gen-sw.mjs. Do not edit: change the generator and rebuild.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(urls, null, 1)};

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(VERSION);
    for (const url of PRECACHE) {
      try {
        const res = await fetch(url, { credentials: 'same-origin' });
        if (!res.ok) continue;
        await cache.put(url, res.clone());
        const html = await res.text();
        const assets = new Set([...html.matchAll(/(?:src|href)="(\\/_next\\/static\\/[^"]+)"/g)].map(m => m[1]));
        for (const a of assets) {
          if (await cache.match(a)) continue;
          try { await cache.add(a); } catch {}
        }
      } catch {}
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== VERSION) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (url.pathname.startsWith('/_next/static/')) { event.respondWith(cacheFirst(req)); return; }
  if (req.mode === 'navigate' || (req.headers.get('accept') || '').includes('text/html')) event.respondWith(networkFirst(req, url));
});

async function cacheFirst(req) {
  const cache = await caches.open(VERSION);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) cache.put(req, res.clone());
  return res;
}

// Pages come from the network when online (so new content shows up) and from the cache when offline.
async function networkFirst(req, url) {
  const cache = await caches.open(VERSION);
  try {
    const res = await fetch(req);
    if (res.ok) cache.put(url.pathname, res.clone());
    return res;
  } catch {
    return (await cache.match(url.pathname)) || (await cache.match(req, { ignoreSearch: true })) ||
      new Response('<!doctype html><meta charset="utf-8"><title>Offline</title><p style="font-family:sans-serif;padding:24px">You are offline and this page is not saved on this device yet. Open it once while online.</p>', { status: 503, headers: { 'content-type': 'text/html' } });
  }
}
`;
fs.writeFileSync(path.join(root, 'public', 'sw.js'), sw);
console.log(`service worker: ${urls.length} pages precached (${version})`);
